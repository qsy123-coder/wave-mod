/** 角色首次卡池日期；非角色分类或未登记返回 null。 */
export function characterReleaseDate(name: string): string | null {
  return CHARACTER_RELEASE_DATES[name.trim()] ?? null;
}

/**
 * 「全部角色分类」的排序：日期新的在前；同日的按拼音（zh-CN，与
 * getAvailableCharacters 的口径一致）；**没登记日期的（UI / 武器 / 怪物 等非角色分类）
 * 一律排在所有角色之后**，彼此之间也按拼音排。
 */
export function compareCharactersByRelease(a: string, b: string): number {
  const dateA = characterReleaseDate(a);
  const dateB = characterReleaseDate(b);

  if (dateA && dateB) {
    // 日期都是 YYYY-MM-DD，字典序即时间序；倒序 = 新的在前
    const byDate = dateB.localeCompare(dateA);
    if (byDate !== 0) return byDate;
  } else if (dateA || dateB) {
    // 只有一个是角色分类：角色在前
    return dateA ? -1 : 1;
  }

  return a.localeCompare(b, "zh-CN");
}

/** 不改入参，返回排好序的新数组。 */
export function sortCharactersByRelease(names: readonly string[]): string[] {
  return [...names].sort(compareCharactersByRelease);
}
